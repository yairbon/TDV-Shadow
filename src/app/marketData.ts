/**
 * Parses `timestamp,o,h,l,c,v` rows into ascending frozen bars.
 *
 * Dates are parsed as UTC midnight: `new Date('2026-08-10')` is already UTC, but
 * appending a time without a zone would be parsed as LOCAL and shift every bar by the
 * runner's offset — which is exactly the local-time arithmetic mandate #5 forbids.
 */
export function parseDailyCsv(csv: string): Bar[] {
  const bars: Bar[] = [];
  for (const line of csv.trim().split('\n')) {
    const parts = line.trim().split(',');
    if (parts.length < 6) continue;
    const time = Date.parse(`${parts[0]}T00:00:00Z`);
    if (!Number.isFinite(time)) continue;
    const bar = makeBar({
      t: time,
      o: Number(parts[1]),
      h: Number(parts[2]),
      l: Number(parts[3]),
      c: Number(parts[4]),
      v: Number(parts[5]),
    });
    if (bar !== null) bars.push(bar);
  }
  // The API returns newest first; every Series invariant assumes ascending time.
  return bars.reverse();
}

export function findSymbol(symbol: string): SymbolDefinition | null {
  return SYMBOLS.find((s) => s.symbol === symbol) ?? null;
}
